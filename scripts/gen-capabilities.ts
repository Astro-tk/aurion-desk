/**
 * Writes a new migration that makes desk.role_capabilities match src/lib/auth/permissions.ts.
 * Run it after changing permissions.ts, then run `npm run db:migrate`.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { capabilityRows } from '../src/lib/auth/permissions';

const dir = join(process.cwd(), 'db', 'migrations');
const last = readdirSync(dir).filter((f) => /^\d{4}_/.test(f)).sort().pop() ?? '0000';
const next = String(Number(last.slice(0, 4)) + 1).padStart(4, '0');
const values = capabilityRows()
  .map(([role, cap]) => `  ('${role}', '${cap}')`)
  .join(',\n');
const file = `${next}_capabilities.sql`;
writeFileSync(
  join(dir, file),
  `-- GENERATED by "npm run gen:capabilities" from src/lib/auth/permissions.ts.
delete from desk.role_capabilities;
insert into desk.role_capabilities (role, capability) values
${values};
`,
);
console.log(`Wrote db/migrations/${file}. Now run: npm run db:migrate`);
